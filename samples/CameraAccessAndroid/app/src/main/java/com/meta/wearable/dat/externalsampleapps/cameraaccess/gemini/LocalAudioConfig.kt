package com.meta.wearable.dat.externalsampleapps.cameraaccess.gemini

/**
 * Endpoints and shared constants for the local audio pipeline
 * (WhisperX STT → LiteLLM → Android TTS). The actual `OpenClawBridge` instance
 * is owned by the ViewModel that needs it; this object is purely config.
 *
 * Environment variables (set at build or runtime):
 *   LITELLM_BASE_URL  – defaults to http://100.105.130.81:4000/v1
 *   WHISPERX_URL      – defaults to http://100.105.130.81:5000/transcribe_base64
 *
 * These can be overridden via BuildConfig fields injected by Gradle
 * (local.properties or a secrets file) so credentials never live in source.
 */
object LocalAudioConfig {

    private const val DEFAULT_LITELLM_BASE_URL = "http://100.105.130.81:4000/v1"
    private const val DEFAULT_WHISPERX_URL = "http://100.105.130.81:5000/transcribe_base64"

    /**
     * Resolves the LiteLLM base URL from BuildConfig when present (injected by
     * Gradle), otherwise falls back to the compiled-in default.  This lets each
     * build variant override the endpoint without touching source code.
     */
    val LITELLM_BASE_URL: String
        get() = try {
            // Generated by Gradle – set via buildConfigField or resValue
            val cls = Class.forName("com.meta.wearable.dat.externalsampleapps.cameraaccess.BuildConfig")
            val field = cls.getDeclaredField("LITELLM_BASE_URL")
            field.isAccessible = true
            field.get(null) as? String ?: DEFAULT_LITELLM_BASE_URL
        } catch (_: Exception) {
            DEFAULT_LITELLM_BASE_URL
        }

    /**
     * Resolves the WhisperX URL the same way.
     */
    val WHISPERX_URL: String
        get() = try {
            val cls = Class.forName("com.meta.wearable.dat.externalsampleapps.cameraaccess.BuildConfig")
            val field = cls.getDeclaredField("WHISPERX_URL")
            field.isAccessible = true
            field.get(null) as? String ?: DEFAULT_WHISPERX_URL
        } catch (_: Exception) {
            DEFAULT_WHISPERX_URL
        }

    const val LITELLM_PORT = 4000
    const val WHISPERX_PORT = 5000

    /** Android TTS engine identifier */
    const val TTS_ENGINE = "com.google.android.tts"

    /**
     * Returns true when the endpoints appear reachable.  During development
     * this is a best-effort check (no network guarantee).
     */
    fun isConfigured(): Boolean = LITELLM_BASE_URL.isNotBlank() && WHISPERX_URL.isNotBlank()
}
